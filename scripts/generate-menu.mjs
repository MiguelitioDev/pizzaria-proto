// Regenerates src/data/menu.ts from data/raw (Yooga API snapshot). Run: node scripts/generate-menu.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const raw = JSON.parse(readFileSync('data/raw/menu.json', 'utf8'))
const images = JSON.parse(readFileSync('data/raw/images.json', 'utf8'))
const cents = (n) => Math.round(n * 100)
const slug = (s) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

const categories = []
const products = []
for (const c of raw) {
  if (!c.items.length) continue // e.g. "CERVEJAS LONG NECK" is empty in the source
  const categoryId = slug(c.name)
  categories.push({ id: categoryId, name: c.name.trim() })
  for (const i of c.items) {
    const optionGroups = []
    for (const ch of i.choices) {
      const seen = new Set()
      const opts = []
      for (const o of ch.options) {
        const key = `${o.name.trim()}|${o.price}`
        if (seen.has(key)) continue // the source repeats entries
        seen.add(key)
        opts.push({ id: `${i.id}-${o.id}`, name: o.name.trim(), price: cents(o.price) })
      }
      const isTwoFlavors = i.name.trim() === 'DOIS SABORES'
      if (isTwoFlavors) {
        // ASSUMPTION (documented in SOURCE_AUDIT.md): "Dois sabores" = exactly two halves.
        // The source allows 0..5 and mixes the REQUEIJÃO add-on into the flavor list.
        optionGroups.push({ id: `${i.id}-sabores`, name: 'Escolha 2 sabores', min: 2, max: 2, options: opts.filter((o) => o.name.startsWith('1/2 ')) })
        optionGroups.push({ id: `${i.id}-adicional`, name: 'Adicional', min: 0, max: 1, options: opts.filter((o) => !o.name.startsWith('1/2 ')) })
      } else {
        optionGroups.push({ id: `${i.id}-${ch.id}`, name: 'Opções disponíveis', min: ch.required ? Math.max(ch.min, 1) : 0, max: ch.max, options: opts })
      }
    }
    const p = { id: String(i.id), categoryId, name: i.name.trim(), description: (i.description ?? '').trim(), basePrice: cents(i.price) }
    if (images[String(i.id)]) p.image = images[String(i.id)]
    p.optionGroups = optionGroups
    products.push(p)
  }
}

const out = `// GENERATED by scripts/generate-menu.mjs from data/raw/menu.json. Do not edit by hand:
// edit prices/products by re-running the script or adjust this file knowingly.
import type { Menu } from '../types'

export const menu: Menu = ${JSON.stringify({ categories, products }, null, 2)}
`
writeFileSync('src/data/menu.ts', out)
console.log(categories.length, 'categories', products.length, 'products')
